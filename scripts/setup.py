"""Interactive local/server setup. Requires Python 3.10+ and Docker Compose v2 only."""

import argparse
import getpass
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
import webbrowser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class SetupError(Exception):
    pass


def run(command, *, capture=False, data=None, env=None):
    result = subprocess.run(
        command,
        cwd=ROOT,
        env=env,
        input=data,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        check=False,
    )
    if result.returncode:
        # Arguments never contain passwords. Docker's own logs identify the failing service.
        raise SetupError(
            "Command failed: " + " ".join(command[:4]) + ". Fix the error and rerun setup."
        )
    return result.stdout or ""


def read_config(path):
    values = {}
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, separator, value = line.partition("=")
            if not separator or not re.fullmatch(r"[A-Z_][A-Z_0-9]*", key):
                raise SetupError("Unsupported .env syntax; use KEY=value lines.")
            values[key] = value.strip().strip("\"'")
    return values


def valid_domain(value):
    if not value:
        return True
    labels = value.split(".")
    return (
        len(value) <= 253
        and len(labels) >= 2
        and not all(label.isdigit() for label in labels)
        and all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", label) for label in labels)
    )


def configure(values, *, domain, port, source_only):
    values = dict(values)
    values["POSTGRES_PASSWORD"] = values.get("POSTGRES_PASSWORD") or secrets.token_hex(32)
    if not re.fullmatch(r"[A-Za-z0-9_-]{16,256}", values["POSTGRES_PASSWORD"]):
        raise SetupError(
            "POSTGRES_PASSWORD must be 16–256 URL-safe letters, digits, underscores or hyphens."
        )
    values["APP_PORT"] = str(port if port is not None else values.get("APP_PORT") or 8000)
    if not values["APP_PORT"].isdigit() or not 1 <= int(values["APP_PORT"]) <= 65535:
        raise SetupError("APP_PORT must be between 1 and 65535.")
    values["APP_DOMAIN"] = (domain if domain is not None else values.get("APP_DOMAIN", "")).lower()
    if not valid_domain(values["APP_DOMAIN"]):
        raise SetupError(
            "Use a public domain such as chat.example.com, without scheme, port or path."
        )
    for key, default in (
        ("OLLAMA_MODEL", "smollm2:360m"),
        ("OLLAMA_EMBED_MODEL", "all-minilm:latest"),
    ):
        values[key] = "" if source_only else values.get(key) or default
        if values[key] and not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.:/-]{0,199}", values[key]):
            raise SetupError("Invalid model tag in " + key)
    if any("\n" in value or "\r" in value for value in values.values()):
        raise SetupError("Configuration values must be single-line.")
    return values


def write_config(path, values):
    # Atomic replacement keeps an interrupted run from losing existing credentials.
    fd, temporary = tempfile.mkstemp(prefix=".env-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as file:
            file.write("# Generated by scripts/setup.py. Keep private; do not commit.\n")
            for key, value in values.items():
                # Preserve literal values rather than letting Compose interpolate dollars.
                if "'" in value:
                    raise SetupError("Single quotes are unsupported in .env values.")
                file.write(f"{key}='{value}'\n")
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def wait_public(url):
    print("Waiting for public HTTPS. This can take up to three minutes.")
    deadline = time.monotonic() + 180
    while True:
        try:
            with urllib.request.urlopen(url + "/health", timeout=10) as response:
                if json.load(response).get("status") == "alive":
                    return
        except (OSError, ValueError, urllib.error.URLError):
            pass
        if time.monotonic() >= deadline:
            raise SetupError(
                "Local application is ready, but public HTTPS is not. Check domain DNS, ports 80/443 and Caddy logs, then rerun setup."
            )
        time.sleep(3)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--domain", help="Public domain; requires DNS pointing to this server and ports 80/443 open"
    )
    parser.add_argument("--port", type=int, help="Local application port, default 8000")
    parser.add_argument(
        "--source-only",
        action="store_true",
        help="Explicitly skip model downloads and use source passages",
    )
    parser.add_argument("--owner-email")
    parser.add_argument("--organization")
    parser.add_argument(
        "--password-stdin",
        action="store_true",
        help="Read initial owner password from stdin, for automation",
    )
    parser.add_argument("--no-browser", action="store_true")
    args = parser.parse_args()
    if not shutil.which("docker"):
        raise SetupError("Install Docker with Compose v2, start Docker, then rerun this command.")
    run(["docker", "compose", "version"], capture=True)
    run(["docker", "info"], capture=True)
    path = ROOT / ".env"
    existing = read_config(path)
    domain = args.domain
    if domain is None and "APP_DOMAIN" not in existing:
        domain = input("Public domain (blank for localhost): ").strip()
    values = configure(existing, domain=domain, port=args.port, source_only=args.source_only)
    write_config(path, values)
    env = {**os.environ, **values}
    command = ["docker", "compose", "--env-file", str(path), "-f", "compose.yaml"]
    if values["APP_DOMAIN"]:
        command += ["-f", "compose.public.yaml"]
        print("HTTPS requires this domain's DNS to point here and inbound TCP 80/443 to be open.")
    else:
        print("Starting on localhost. Database and model ports remain private.")

    def compose(*parts, capture=False, data=None):
        return run(command + list(parts), capture=capture, data=data, env=env)

    # Start the private stack first. Public routing is enabled after account/readiness checks.
    compose(
        "up", "--build", "-d", "--wait", "--wait-timeout", "180", "db", "ollama", "api", "worker"
    )
    for key in ("OLLAMA_MODEL", "OLLAMA_EMBED_MODEL"):
        if values[key]:
            print("Preparing model:", values[key])
            compose("exec", "-T", "ollama", "ollama", "pull", values[key])
    status = json.loads(
        compose(
            "exec", "-T", "api", "python", "-m", "platform_api.bootstrap", "--status", capture=True
        )
    )
    document_id = status.get("document_id")
    if not status["initialized"]:
        email = args.owner_email or input("Owner email: ").strip()
        name = args.organization or input("Organisation name: ").strip()
        if args.password_stdin:
            password = sys.stdin.readline().rstrip("\r\n")
        else:
            password = getpass.getpass("Choose a password (16–256 characters): ")
            if password != getpass.getpass("Repeat password: "):
                raise SetupError("Passwords did not match. Rerun setup to finish account creation.")
        # Send the secret over stdin, never in process arguments or the saved .env.
        payload = json.dumps({"email": email, "name": name, "password": password})
        result = json.loads(
            compose(
                "exec",
                "-T",
                "api",
                "python",
                "-m",
                "platform_api.bootstrap",
                "--stdin",
                capture=True,
                data=payload,
            )
        )
        document_id = result.get("document_id")
    else:
        print("Existing accounts preserved. Sign in with your current credentials.")
    check = ["exec", "-T", "api", "python", "-m", "platform_api.readiness"]
    if document_id:
        check += ["--document", document_id]
    compose(*check)
    if values["APP_DOMAIN"]:
        compose("up", "-d", "caddy")
        url = "https://" + values["APP_DOMAIN"]
        wait_public(url)
    else:
        url = "http://localhost:" + values["APP_PORT"]
    print("Setup complete. Sign in at " + url)
    print(
        "Ask: How do I upload my business documents? Then replace the starter guide with your information."
    )
    if not args.no_browser:
        webbrowser.open(url)


if __name__ == "__main__":
    try:
        main()
    except (SetupError, OSError, ValueError) as exc:
        print("Setup stopped: " + str(exc), file=sys.stderr)
        sys.exit(1)
    except (KeyboardInterrupt, EOFError):
        print("\nSetup interrupted. Rerun the same command to continue.", file=sys.stderr)
        sys.exit(1)
